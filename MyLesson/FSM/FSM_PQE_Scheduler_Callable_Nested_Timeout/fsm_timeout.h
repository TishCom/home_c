#ifndef FSM_TIMEOUT_H_
#define FSM_TIMEOUT_H_

#include <stdbool.h>
#include <inttypes.h>
#include "fsm.h"
#include "fsm_scheduler.h"

/* ================================================================
 * ТИП ДАННЫХ ДЛЯ ТАЙМАУТА
 * ================================================================ */

/* Структура данных таймаута (хранится в FSM) */
typedef struct 
{
    uint32_t timeout_ms;                /* Таймаут в миллисекундах (0 = без таймаута) */
    uint32_t start_tick;                /* Время старта (тик планировщика) */
    bool timeout_occurred;              /* Флаг: таймаут сработал */
    bool timeout_enabled;               /* Флаг: таймаут активен */
    void (*on_timeout)(void *context);  /* Обработчик таймаута */
} FSMLocalTimer;

/* ================================================================
 * ТИП ФУНКЦИИ ДЛЯ ПОЛУЧЕНИЯ ТЕКУЩЕГО ВРЕМЕНИ
 * ================================================================ */

/* Тип функции для получения времени в миллисекундах */
typedef uint32_t (*fsmTimerGetTickFunc)(void);

/* ================================================================
 * УПРАВЛЕНИЕ ЖИЗНЕННЫМ ЦИКЛОМ ТАЙМАУТА
 * ================================================================ */

/*операция:     оформление данных таймаута для автомата                                         */
/*предусловия:  в timer находится заполненная структура(шаблон) таймаута для автомата           */
/*постусловия:  инициализация данных таймаута автомата значениями из передпнного шаблона,       */
/*              функция возвращает адрес оформленных данных или NULL если данные создать не     */
/*              удалось                                                                         */
FSMLocalTimer* fsmTimerCreate(FSMLocalTimer timer);

/*операция:     освобождение памяти выделенной для данных таймаута автомату                     */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  памяти выделенная для данных необходимых таймаута автомата освобождается        */
void fsmTimerDestroy(FSM *machine);

/*операция:     сброс данных таймаута в начальное состояние                                     */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  таймаут сброшен в неактивное состояние                                          */
void fsmTimerReset(FSM *machine);

/*операция:     проверка, являются ли данные необходимые таймауту автомата инициализироваными   */
/*предусловия:  в timer находится предположительно инициализированные данные таймаута автомата  */
/*постусловия:  функция возвращает true если данные инициализированы и false в противном случае */
bool fsmTimerIsInitialise(const FSMLocalTimer *timer);

/*операция:     проверка, являются ли данные необходимые таймауту автомата инициализироваными   */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  функция возвращает true если данные инициализированы и false в противном случае */
bool fsmTimerIsReady(const FSM *machine);

/* ================================================================
 * УСТАНОВКА И УПРАВЛЕНИЕ ТАЙМАУТОМ
 * ================================================================ */

/*операция:     установить таймаут для автомата                                                 */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*              в timeout_ms находится время таймаута в миллисекундах                           */
/*              в on_timeout находится функция-обработчик таймаута                              */
/*постусловия:  для автомата установлен таймаут, если установка удалась то возвращяется true    */
/*              в противном случае false                                                        */
bool fsmTimerSetTimeout(FSM *machine, uint32_t timeout_ms, void (*on_timeout)(void *context));

/*операция:     сбросить таймаут для автомата                                                   */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  таймаут для автомата сброшен и отключен                                         */
void fsmTimerClearTimeout(FSM *machine);

/*операция:     обновить время старта таймаута (продлить таймаут)                               */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  счетчик таймаута сброшен на текущее время                                       */
void fsmTimerRefreshTimeout(FSM *machine);

/*операция:     установка значения таймаута автомата                                            */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*              в timeout_ms находится время которое мы устанавливаем для таймаута в            */
/*              миллисекундах                                                                   */
/*постусловия:  установлено новое значение таймаута автомата                                    */
void fsmTimerSetTimeoutValue(FSM *machine, uint32_t timeout_ms);

/*операция:     получение значения таймаута автомата                                            */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*              в timeout_ms будут находится данные значения таймаута автомата                  */
/*постусловия:  функция возвращает true если данные были считаны и false в проивном случае      */
bool fsmTimerGetTimeout(const FSM *machine, uint32_t *timeout_ms);

/*операция:     установка значения времени старта автомата                                      */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*              в start_tick находится время которое мы устанавливаем для времени старта        */
/*              автомата в миллисекундах                                                        */
/*постусловия:  установлено новое значение времени старта автомата                              */
void fsmTimerSetStart(FSM *machine, uint32_t start_tick);

/*операция:     получение значения времени старта автомата                                      */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*              в start_tick будут находится данные значения времени старта автомата            */
/*постусловия:  функция возвращает true если данные были считаны и false в проивном случае      */
bool fsmTimerGetStart(const FSM *machine, uint32_t *start_tick);

/*операция:     установка таймера автомата как сработавшего                                     */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  таймер автомата помечается как сработавший                                      */
void fsmTimerSetOccurred(FSM *machine);

/*операция:     установка таймера автомата как не сработавшего                                  */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  таймера автомата помечается как не сработавший                                  */
void fsmTimerResetOccurred(FSM *machine);

/*операция:     установка таймера автомата как активного                                        */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  таймера автомата помечается как активный                                        */
void fsmTimerSetEnable(FSM *machine);

/*операция:     установка таймера автомата как не активного                                     */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  таймера автомата помечается как не активный                                     */
void fsmTimerResetEnable(FSM *machine);

/* ================================================================
 * ПРОВЕРКА ТАЙМАУТА
 * ================================================================ */

/*операция:     проверить, не истек ли таймаут                                                  */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  возвращает true если таймаут истек, false в противном случае                    */
bool fsmTimerIsExpired(const FSM *machine);

/*операция:     проверка, является ли автомат активным                                          */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  функция возвращает true если автомат активен и false в противном случае         */
bool fsmTimerIsEnable(const FSM *machine);

/*операция:     проверка, является ли автомат выполненным                                       */
/*предусловия:  в machine находится инициализированный автомат                                  */
/*постусловия:  функция возвращает true если автомат выполнен и false в противном случае        */
bool fsmTimerIsOccurred(const FSM *machine);

/* ================================================================
 * ОБРАБОТКА ТАЙМАУТА В ПЛАНИРОВЩИКЕ
 * ================================================================ */

/*операция:     проверить таймауты всех автоматов в планировщике                                */
/*предусловия:  в sched находится инициализированный планировщик                                */
/*постусловия:  для автоматов, у которых истек таймаут, вызывается обработчик                   */
void fsmTimerCheckAllTimeouts(FSMScheduler *sched);

/* ================================================================
 * ПОЛУЧЕНИЕ ТЕКУЩЕГО ВРЕМЕНИ (УКАЗАТЕЛЬ НА ФУНКЦИЮ)
 * ================================================================ */

/*операция:     установка пользовательской функции получения времени                            */
/*предусловия:  в func находится указатель на функцию, возвращающую текущее время               */
/*              в миллисекундах                                                                 */
/*постусловия:  установлена функция для получения времени                                       */
void fsmTimerSetTickFunction(fsmTimerGetTickFunc func);

/*операция:     получить текущее время в миллисекундах                                          */
/*предусловия:  должна быть установлена функция через fsmTimerSetTickFunction()                 */
/*постусловия:  функция возвращает текущее время в миллисекундах, возвращает 0 в случае         */
/*              если функция не установленна                                                    */
uint32_t fsmTimerGetCurrentTick(void);

#endif