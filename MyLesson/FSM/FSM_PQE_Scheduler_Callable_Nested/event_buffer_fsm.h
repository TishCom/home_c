#ifndef EVENT_BUFFER_FSM_H_
#define EVENT_BUFFER_FSM_H_

#include <stdbool.h>
#include <inttypes.h>
#include <stdlib.h>

/*Библиотека необхадимая для работы с конечным астоматом*/
#include "fsm.h"

// Структура типа данных для кольцевого буфера
typedef struct
{
    EventFSM *data;
    uint32_t head;
    uint32_t tail;
    uint32_t capacity;
    uint32_t items;
    bool overwrite_mode;
} EventBufferFSM;

/*операция:     инициализация буфера событий                                                    */
/*предусловия:  size - размер буфера событий                                                    */
/*постусловия:  функция возвращает указатель на инициализированных буфер событий для конечного  */
/*              автомата                                                                        */
EventBufferFSM* initializeBufferFSM(uint32_t size);

/*операция:     освобождение выделенной памяти если она есть                                    */
/*предусловия:  machine указывает на ранее инициализированный конечный автомат                  */
/*постусловия:  любая память выделенная для конечного автомата, освобождается,                  */
/*              и конечный автомат устанавливается в пустое состояние                           */
void emptyBufferFSM(FSM *machine);

/*операция:     добавить событие в очередь событий автомата                                     */
/*предусловия:  machine указывает на инициализированный конечный автомат,                       */ 
/*              в event находится событие кторое будем записвать в очередь                      */
/*постусловия:  добавили событие в очередь конечного автомата,                                  */
/*              если priority == 0, то событие помещается в конец очереди (FIFO),               */
/*              если priority > 0,  то событие вставляется согласно приоритету                  */
/*              (чем больше priority, тем раньше будет обработано),                             */
/*              функция возвращает false если не удалось добавить событие,                      */
/*              и true в противном случае                                                       */
bool pushEventQueue(FSM *machine, EventFSM event);

/*операция:     взять событие из очереди событий автомата                                       */
/*предусловия:  machine указывает на инициализированный конечный автомат,                       */ 
/*              в event будет записано событие кторое прочитаем из очереди                      */
/*постусловия:  взяли событие из очеред конечного автомата и удалили его из очереди, функция    */
/*              возвращает false если не удалось взять событие и true в противном случае        */
bool popEventQueue(FSM *machine, EventFSM *event);

/*операция:     проверка, является ли очередь событий пустой                                    */
/*предусловия:  machine указывает на инициализированный конечный автомат                        */
/*постусловия:  функция возвращает false если очередь не пуста и true в противном случае        */
bool queueEventIsEmpty(const FSM *machine);

/*операция:     обработать все события из очереди автомата                                      */
/*предусловия:  machine указывает на инициализированный конечный автомат                        */
/*постусловия:  функция обрабатывает все события из очереди событий автомата, функция           */
/*              возвращает количество обработанных событий                                      */
uint32_t fsmProcessQueue(FSM *machine);

#endif