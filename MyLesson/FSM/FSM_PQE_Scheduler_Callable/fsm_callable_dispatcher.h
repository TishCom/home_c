#ifndef FSM_CALLABLE_DISPATCHER_H_
#define FSM_CALLABLE_DISPATCHER_H_

#include <stdbool.h>
#include <inttypes.h>
#include "fsm.h"
#include "fsm_callable.h"
#include "event_buffer_fsm.h"

/* ================================================================
 * ДИСПЕТЧЕРИЗАЦИЯ С ПОДДЕРЖКОЙ ВЫЗЫВАЕМЫХ АВТОМАТОВ
 * ================================================================ */

/*операция:     обработка одного события с автоматической проверкой завершения вызываемого      */
/*              автомата                                                                        */
/*предусловия:  в machine находится инициализированный конечный автомат,                        */
/*              в event находится событие которое необходимо обработать                         */
/*постусловия:  если автомат вызываемый и после обработки события его состояние совпадает с     */
/*              finish_state, автоматически вызывается fsmReturn(), функция возвращает true если*/
/*              событие обработано и false в противном случае                                   */
bool fsmCallableDispatch(FSM *machine, EventFSM event);

/*операция:     обработка всех событий из очереди автомата с поддержкой вызываемых автоматов    */
/*предусловия:  в machine находится инициализированный конечный автомат                         */
/*постусловия:  Аналог fsmProcessQueue, но с автоматической проверкой finish_state. Используется*/
/*              в планировщике вместо fsmProcessQueue, функция возвращает количество            */
/*              обработанных событий                                                            */
uint32_t fsmProcessCallable(FSM *machine);

#endif